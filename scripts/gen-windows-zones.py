#!/usr/bin/env python3
"""Generate crates/mp-core/src/windows_zones.rs from CLDR's windowsZones.xml
and its time zone aliases (common/bcp47/timezone.xml).

Graph and EWS name an event's time zone the Windows way ("W. Europe Standard
Time"); the calendar model stores IANA zones (PERSO-200). CLDR maps each
Windows zone to the IANA zone of its territory "001" entry, the zone Windows
itself treats as canonical, which is the table a read uses.

A write goes the other way (PERSO-255) and starts from any IANA zone, the
system's own included (`Europe/Vienna`, `Asia/Kolkata`), so the reverse table
takes every mapZone row of every territory, plus each alias CLDR lists for a
zone it maps, since CLDR keeps the legacy names (`Asia/Calcutta`,
`Europe/Kiev`) that a system names by their current spelling.

Run from the repository root:

    uv run scripts/gen-windows-zones.py [COMMIT]

With no COMMIT the generator reads CLDR's `main`; give the commit the current
table names in its header to regenerate it from the same data. Stdlib only.
The commit is pinned in the output header, so a rerun that changes the table
shows up as a diff.
"""

import json
import pathlib
import sys
import urllib.request
import xml.etree.ElementTree as ET

BRANCH = "main"
COMMITS_URL = f"https://api.github.com/repos/unicode-org/cldr/commits/{BRANCH}"
RAW_URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr/{ref}"
    "/common/supplemental/windowsZones.xml"
)
ALIASES_URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr/{ref}"
    "/common/bcp47/timezone.xml"
)
SOURCE_URL = RAW_URL.format(ref=BRANCH)
ALIASES_SOURCE_URL = ALIASES_URL.format(ref=BRANCH)
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / (
    "crates/mp-core/src/windows_zones.rs"
)


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "mailypoppins-gen"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def head_commit() -> str:
    """The commit `main` points at, so the table names exactly what it read."""
    return json.loads(fetch(COMMITS_URL))["sha"]


def parse(xml: bytes) -> tuple[str, list[tuple[str, str]], dict[str, str]]:
    """The data versions, the forward table (each Windows zone to its "001"
    IANA zone) and the reverse map (every IANA zone of every row to its
    Windows zone)."""
    root = ET.fromstring(xml)
    # The file carries no CLDR release number; the versions of the Windows
    # zone data and of the tz database it was mapped against are what it has.
    zones = root.find("windowsZones/mapTimezones")
    cldr_version = (
        f"Windows zone data {zones.get('otherVersion', '?')}, "
        f"tz {zones.get('typeVersion', '?')}"
    )
    pairs = {}
    reverse: dict[str, str] = {}
    for zone in root.iter("mapZone"):
        windows = zone.get("other")
        names = zone.get("type").split()
        for iana in names:
            known = reverse.setdefault(iana, windows)
            # A zone may repeat across rows, but only under one Windows zone.
            assert known == windows, f"{iana} maps to both {known} and {windows}"
        if zone.get("territory") == "001":
            # The "001" entry carries one IANA name; split defensively anyway.
            pairs[windows] = names[0]
    return cldr_version, sorted(pairs.items()), reverse


def add_aliases(reverse: dict[str, str], xml: bytes) -> None:
    """Every alias of a zone `reverse` maps, under the same Windows zone:
    CLDR's `alias` lists a zone's names, the legacy one it maps by first."""
    root = ET.fromstring(xml)
    for zone in root.iter("type"):
        names = (zone.get("alias") or "").split()
        if zone.get("iana"):
            names.append(zone.get("iana"))
        windows = {reverse[name] for name in names if name in reverse}
        assert len(windows) <= 1, f"the aliases {names} map to {sorted(windows)}"
        if windows:
            (target,) = windows
            for name in names:
                reverse.setdefault(name, target)


def render(
    cldr_version: str,
    commit: str,
    pairs: list[tuple[str, str]],
    reverse: list[tuple[str, str]],
) -> str:
    rows = "\n".join(f'    ("{w}", "{i}"),' for w, i in pairs)
    reverse_rows = "\n".join(f'    ("{i}", "{w}"),' for i, w in reverse)
    return f"""//! Windows time zone names to IANA zones and back (PERSO-200, PERSO-255).
//!
//! GENERATED by `scripts/gen-windows-zones.py`; do not edit by hand.
//! Sources: {SOURCE_URL}
//! and {ALIASES_SOURCE_URL},
//! unicode-org/cldr commit {commit} ({cldr_version}).
//!
//! Graph and EWS name an event's zone the Windows way
//! (`W. Europe Standard Time`); the calendar model stores IANA zones. Each
//! Windows zone maps to the IANA zone of its CLDR territory "001" entry.
//! The way back maps every IANA zone CLDR lists under a Windows zone, for any
//! territory, and every alias of one, so a write names the zone of an event
//! in Vienna or Kolkata as Graph knows it.

use std::str::FromStr;

/// `(windows_name, iana_name)`, sorted by the Windows name.
pub static WINDOWS_ZONES: &[(&str, &str)] = &[
{rows}
];

/// `(iana_name, windows_name)` for every IANA zone and alias CLDR maps,
/// sorted by the IANA name. One row per line, as generated: rustfmt would
/// split the longest.
#[rustfmt::skip]
pub static IANA_ZONES: &[(&str, &str)] = &[
{reverse_rows}
];

/// The IANA zone of a Windows zone name, or `None` for a name CLDR does not
/// list (`tzone://Microsoft/Custom`, a zone Outlook built from a custom rule).
pub fn windows_zone_to_iana(windows: &str) -> Option<&'static str> {{
    WINDOWS_ZONES
        .binary_search_by(|(name, _)| (*name).cmp(windows))
        .ok()
        .map(|index| WINDOWS_ZONES[index].1)
}}

/// The IANA zone a server zone name means: an IANA name chrono-tz knows
/// passes through, a Windows name is mapped, anything else is `None`.
pub fn iana_or_windows(name: &str) -> Option<String> {{
    let name = name.trim();
    if name.is_empty() {{
        return None;
    }}
    if let Some(iana) = windows_zone_to_iana(name) {{
        return Some(iana.to_string());
    }}
    chrono_tz::Tz::from_str(name)
        .ok()
        .map(|tz| tz.name().to_string())
}}

/// The Windows zone name of an IANA zone or alias, from [`IANA_ZONES`];
/// `None` for a zone CLDR maps to no Windows zone (`Antarctica/Troll`),
/// which a calendar write sends as UTC, with the instants exact.
pub fn iana_to_windows_zone(iana: &str) -> Option<&'static str> {{
    let iana = iana.trim();
    IANA_ZONES
        .binary_search_by(|(name, _)| (*name).cmp(iana))
        .ok()
        .map(|index| IANA_ZONES[index].1)
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn the_table_is_sorted_and_every_target_is_a_known_iana_zone() {{
        assert!(WINDOWS_ZONES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (windows, iana) in WINDOWS_ZONES {{
            assert!(
                chrono_tz::Tz::from_str(iana).is_ok(),
                "{{windows}} maps to {{iana}}, which chrono-tz does not know"
            );
        }}
    }}

    #[test]
    fn known_windows_names_map_to_their_iana_zone() {{
        assert_eq!(
            windows_zone_to_iana("W. Europe Standard Time"),
            Some("Europe/Berlin")
        );
        assert_eq!(
            windows_zone_to_iana("GMT Standard Time"),
            Some("Europe/London")
        );
        assert_eq!(
            windows_zone_to_iana("Pacific Standard Time"),
            Some("America/Los_Angeles")
        );
        assert_eq!(windows_zone_to_iana("UTC"), Some("Etc/UTC"));
    }}

    #[test]
    fn a_custom_or_unknown_zone_maps_to_nothing() {{
        assert_eq!(windows_zone_to_iana("tzone://Microsoft/Custom"), None);
        assert_eq!(iana_or_windows("tzone://Microsoft/Custom"), None);
        assert_eq!(iana_or_windows(""), None);
        assert_eq!(iana_or_windows("Not A Zone"), None);
    }}

    #[test]
    fn an_iana_name_passes_through_and_a_windows_name_is_mapped() {{
        assert_eq!(
            iana_or_windows("Europe/Paris").as_deref(),
            Some("Europe/Paris")
        );
        assert_eq!(
            iana_or_windows(" W. Europe Standard Time ").as_deref(),
            Some("Europe/Berlin")
        );
    }}

    #[test]
    fn the_reverse_table_is_sorted_and_names_known_windows_zones() {{
        assert!(IANA_ZONES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (iana, windows) in IANA_ZONES {{
            assert!(
                windows_zone_to_iana(windows).is_some(),
                "{{iana}} maps to {{windows}}, which the forward table lacks"
            );
        }}
    }}

    #[test]
    fn every_iana_zone_of_the_table_maps_back_to_its_windows_name() {{
        for (windows, iana) in WINDOWS_ZONES {{
            assert_eq!(iana_to_windows_zone(iana), Some(*windows), "{{iana}}");
        }}
        assert_eq!(
            iana_to_windows_zone(" Europe/Berlin "),
            Some("W. Europe Standard Time")
        );
        assert_eq!(iana_to_windows_zone("Etc/UTC"), Some("UTC"));
        assert_eq!(iana_to_windows_zone("UTC"), Some("UTC"));
        assert_eq!(iana_to_windows_zone("Antarctica/Troll"), None);
        assert_eq!(iana_to_windows_zone(""), None);
    }}

    /// A zone CLDR lists only under its own territory, and the current
    /// spelling of a zone CLDR maps by its legacy name, map back too.
    #[test]
    fn regional_zones_and_current_spellings_map_back() {{
        for (iana, windows) in [
            ("Europe/Vienna", "W. Europe Standard Time"),
            ("Europe/Zurich", "W. Europe Standard Time"),
            ("Europe/Rome", "W. Europe Standard Time"),
            ("America/Toronto", "Eastern Standard Time"),
            ("Asia/Kolkata", "India Standard Time"),
            ("Asia/Calcutta", "India Standard Time"),
            ("Europe/Kyiv", "FLE Standard Time"),
            ("Europe/Kiev", "FLE Standard Time"),
            ("Asia/Kathmandu", "Nepal Standard Time"),
            ("America/Argentina/Buenos_Aires", "Argentina Standard Time"),
        ] {{
            assert_eq!(iana_to_windows_zone(iana), Some(windows), "{{iana}}");
        }}
    }}
}}
"""


def main() -> None:
    commit = sys.argv[1] if len(sys.argv) > 1 else head_commit()
    cldr_version, pairs, reverse = parse(fetch(RAW_URL.format(ref=commit)))
    add_aliases(reverse, fetch(ALIASES_URL.format(ref=commit)))
    OUTPUT.write_text(render(cldr_version, commit, pairs, sorted(reverse.items())))
    print(
        f"wrote {len(pairs)} zones and {len(reverse)} reverse names "
        f"({cldr_version}, {commit[:12]}) to {OUTPUT}"
    )


if __name__ == "__main__":
    main()

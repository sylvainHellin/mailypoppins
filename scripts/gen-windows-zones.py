#!/usr/bin/env python3
"""Generate crates/mp-core/src/windows_zones.rs from CLDR's windowsZones.xml.

Graph and EWS name an event's time zone the Windows way ("W. Europe Standard
Time"); the calendar model stores IANA zones (PERSO-200). CLDR maps each
Windows zone to the IANA zone of its territory "001" entry, the zone Windows
itself treats as canonical.

Run from the repository root:

    uv run scripts/gen-windows-zones.py

Stdlib only. The commit the table was generated from is pinned in the output
header, so a rerun that changes the table shows up as a diff.
"""

import json
import pathlib
import urllib.request
import xml.etree.ElementTree as ET

BRANCH = "main"
COMMITS_URL = f"https://api.github.com/repos/unicode-org/cldr/commits/{BRANCH}"
RAW_URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr/{ref}"
    "/common/supplemental/windowsZones.xml"
)
SOURCE_URL = RAW_URL.format(ref=BRANCH)
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / (
    "crates/mp-core/src/windows_zones.rs"
)


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "mailypoppins-gen"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def head_commit() -> str:
    """The commit `main` points at, so the table names exactly what it read."""
    return json.loads(fetch(COMMITS_URL))["sha"]


def parse(xml: bytes) -> tuple[str, list[tuple[str, str]]]:
    root = ET.fromstring(xml)
    # The file carries no CLDR release number; the versions of the Windows
    # zone data and of the tz database it was mapped against are what it has.
    zones = root.find("windowsZones/mapTimezones")
    cldr_version = (
        f"Windows zone data {zones.get('otherVersion', '?')}, "
        f"tz {zones.get('typeVersion', '?')}"
    )
    pairs = {}
    for zone in root.iter("mapZone"):
        if zone.get("territory") != "001":
            continue
        windows = zone.get("other")
        # The "001" entry carries one IANA name; split defensively anyway.
        iana = zone.get("type").split()[0]
        pairs[windows] = iana
    return cldr_version, sorted(pairs.items())


def render(cldr_version: str, commit: str, pairs: list[tuple[str, str]]) -> str:
    rows = "\n".join(f'    ("{w}", "{i}"),' for w, i in pairs)
    return f"""//! Windows time zone names to IANA zones (PERSO-200).
//!
//! GENERATED by `scripts/gen-windows-zones.py`; do not edit by hand.
//! Source: {SOURCE_URL}
//! unicode-org/cldr commit {commit} ({cldr_version}).
//!
//! Graph and EWS name an event's zone the Windows way
//! (`W. Europe Standard Time`); the calendar model stores IANA zones. Each
//! Windows zone maps to the IANA zone of its CLDR territory "001" entry.

use std::str::FromStr;

/// `(windows_name, iana_name)`, sorted by the Windows name.
pub static WINDOWS_ZONES: &[(&str, &str)] = &[
{rows}
];

/// The IANA zone of a Windows zone name, or `None` for a name CLDR does not
/// list (`tzone://Microsoft/Custom`, a zone Outlook built from a custom rule).
pub fn windows_zone_to_iana(windows: &str) -> Option<&'static str> {{
    WINDOWS_ZONES
        .binary_search_by(|(name, _)| (*name).cmp(windows))
        .ok()
        .map(|index| WINDOWS_ZONES[index].1)
}}

/// The IANA zone a server zone name means: an IANA name chrono-tz knows
/// passes through, a Windows name is mapped, anything else is `None`.
pub fn iana_or_windows(name: &str) -> Option<String> {{
    let name = name.trim();
    if name.is_empty() {{
        return None;
    }}
    if let Some(iana) = windows_zone_to_iana(name) {{
        return Some(iana.to_string());
    }}
    chrono_tz::Tz::from_str(name)
        .ok()
        .map(|tz| tz.name().to_string())
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn the_table_is_sorted_and_every_target_is_a_known_iana_zone() {{
        assert!(WINDOWS_ZONES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (windows, iana) in WINDOWS_ZONES {{
            assert!(
                chrono_tz::Tz::from_str(iana).is_ok(),
                "{{windows}} maps to {{iana}}, which chrono-tz does not know"
            );
        }}
    }}

    #[test]
    fn known_windows_names_map_to_their_iana_zone() {{
        assert_eq!(
            windows_zone_to_iana("W. Europe Standard Time"),
            Some("Europe/Berlin")
        );
        assert_eq!(
            windows_zone_to_iana("GMT Standard Time"),
            Some("Europe/London")
        );
        assert_eq!(
            windows_zone_to_iana("Pacific Standard Time"),
            Some("America/Los_Angeles")
        );
        assert_eq!(windows_zone_to_iana("UTC"), Some("Etc/UTC"));
    }}

    #[test]
    fn a_custom_or_unknown_zone_maps_to_nothing() {{
        assert_eq!(windows_zone_to_iana("tzone://Microsoft/Custom"), None);
        assert_eq!(iana_or_windows("tzone://Microsoft/Custom"), None);
        assert_eq!(iana_or_windows(""), None);
        assert_eq!(iana_or_windows("Not A Zone"), None);
    }}

    #[test]
    fn an_iana_name_passes_through_and_a_windows_name_is_mapped() {{
        assert_eq!(
            iana_or_windows("Europe/Paris").as_deref(),
            Some("Europe/Paris")
        );
        assert_eq!(
            iana_or_windows(" W. Europe Standard Time ").as_deref(),
            Some("Europe/Berlin")
        );
    }}
}}
"""


def main() -> None:
    commit = head_commit()
    xml = fetch(RAW_URL.format(ref=commit))
    cldr_version, pairs = parse(xml)
    OUTPUT.write_text(render(cldr_version, commit, pairs))
    print(f"wrote {len(pairs)} zones ({cldr_version}, {commit[:12]}) to {OUTPUT}")


if __name__ == "__main__":
    main()
